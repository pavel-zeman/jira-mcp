// Converts the Atom feed served by the Atlassian Activity Streams plugin (/activity) into plain-text entries

export interface ActivityEntry {
  published: string;
  author: {
    name?: string;
    username?: string;
  };
  // e.g. "Jane Doe changed the status to Done on PROJ-1 - Summary"
  title: string;
  // Details such as the comment text or the list of changed fields
  content?: string;
  link?: string;
  issueKey?: string;
}

interface XmlNode {
  // Local name only: namespace prefixes (activity:, usr:, ...) are dropped
  name: string;
  attributes: Record<string, string>;
  children: XmlNode[];
  text: string;
}

// The feed is well-formed XML generated by Jira, so a tokenizer is enough and nothing is validated.
// Groups: 1 CDATA, 2 tag name, 3 attributes, 4 self-closing slash, 5 text. Comments, <?...?>, <!...> and closing tags have no group.
const XML_TOKEN = /<!\[CDATA\[([\s\S]*?)\]\]>|<!--[\s\S]*?-->|<[?!][^>]*>|<\/[^>]*>|<([^\s/>]+)((?:[^>"']|"[^"]*"|'[^']*')*?)(\/?)>|([^<]+)/g;
const XML_ATTRIBUTE = /([^\s=]+)\s*=\s*(?:"([^"]*)"|'([^']*)')/g;
const ENTITIES = new Map([['lt', '<'], ['gt', '>'], ['amp', '&'], ['quot', '"'], ['apos', "'"], ['nbsp', ' ']]);

function decodeEntities(text: string): string {
  return text.replace(/&(?:#(\d+)|#x([\da-f]+)|(\w+));/gi, (match, decimal?: string, hex?: string, named?: string) => {
    if (named) {
      return ENTITIES.get(named) ?? match;
    }
    const codePoint = decimal ? parseInt(decimal, 10) : parseInt(hex!, 16);
    return codePoint <= 0x10ffff ? String.fromCodePoint(codePoint) : match;
  });
}

function parseXml(xml: string): XmlNode {
  const root: XmlNode = { name: '', attributes: {}, children: [], text: '' };
  const stack = [root];

  for (const [token, cdata, tagName, attributes, selfClosing, text] of xml.matchAll(XML_TOKEN)) {
    const parent = stack[stack.length - 1];
    if (cdata !== undefined) {
      parent.text += cdata;
    } else if (text !== undefined) {
      parent.text += decodeEntities(text);
    } else if (tagName !== undefined) {
      const node: XmlNode = { name: tagName.slice(tagName.indexOf(':') + 1), attributes: {}, children: [], text: '' };
      for (const [, attrName, doubleQuoted, singleQuoted] of attributes.matchAll(XML_ATTRIBUTE)) {
        node.attributes[attrName.slice(attrName.indexOf(':') + 1)] = decodeEntities(doubleQuoted ?? singleQuoted);
      }
      parent.children.push(node);
      if (!selfClosing) {
        stack.push(node);
      }
    } else if (token.startsWith('</') && stack.length > 1) {
      stack.pop();
    }
  }

  return root;
}

function child(node: XmlNode | undefined, name: string): XmlNode | undefined {
  return node?.children.find(c => c.name === name);
}

// Keeps paragraphs and list items on separate lines but drops all markup
function htmlToText(html: string): string {
  const text = html
    .replace(/\s+/g, ' ')
    .replace(/<br\s*\/?>|<\/(?:p|div|h[1-6]|li|tr|pre|blockquote)>/gi, '\n')
    .replace(/<li\b[^>]*>/gi, '- ')
    .replace(/<[^>]*>/g, '');
  return decodeEntities(text)
    .replace(/[^\S\n]+/g, ' ')
    .replace(/ *\n[\n ]*/g, '\n')
    .trim();
}

// Atom text constructs carry escaped HTML when type="html"
function textOf(node: XmlNode | undefined): string | undefined {
  if (!node) {
    return undefined;
  }
  return node.attributes.type === 'html' ? htmlToText(node.text) : node.text.trim();
}

function toActivityEntry(entry: XmlNode): ActivityEntry {
  const author = child(entry, 'author');
  // An issue is either the activity's object (issue created/updated) or its target (comment posted on an issue)
  const issue = [child(entry, 'object'), child(entry, 'target')]
    .find(node => child(node, 'object-type')?.text.trim().endsWith('/issue'));

  return {
    published: textOf(child(entry, 'published')) ?? textOf(child(entry, 'updated')) ?? '',
    author: {
      name: textOf(child(author, 'name')),
      username: textOf(child(author, 'username')),
    },
    title: textOf(child(entry, 'title')) ?? '',
    content: textOf(child(entry, 'content') ?? child(entry, 'summary')) || undefined,
    // Atom links without rel are alternate links
    link: entry.children.find(c => c.name === 'link' && (c.attributes.rel ?? 'alternate') === 'alternate')?.attributes.href,
    issueKey: textOf(child(issue, 'title')),
  };
}

export function parseActivityFeed(xml: string): ActivityEntry[] {
  const feed = child(parseXml(xml), 'feed');
  if (!feed) {
    // e.g. an SSO login page served by a reverse proxy in place of the feed
    throw new Error('Unexpected activity stream response: expected an Atom feed');
  }
  return feed.children.filter(c => c.name === 'entry').map(toActivityEntry);
}
